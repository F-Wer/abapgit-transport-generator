"""Function group source collection for abapGit transport generation."""

import html
import re
from pathlib import Path
from typing import Callable, Type

BuildReposKey = Callable[[str, str, str], str]


def parse_fugr_xml(xml_path: Path) -> dict:
    """Read abapGit .fugr.xml group text and function module list."""
    if xml_path is None or not Path(xml_path).exists():
        return {"areat": "", "functions": [], "interfaces": {}}
    text = Path(xml_path).read_text(encoding="utf-8", errors="replace")
    out = {"areat": "", "functions": [], "interfaces": {}}
    match = re.search(r"<AREAT>([^<]*)</AREAT>", text, re.IGNORECASE)
    if match:
        out["areat"] = html.unescape(match.group(1).strip())
    match = re.search(r"<FUNCTIONS>(.*?)</FUNCTIONS>", text,
                      re.IGNORECASE | re.DOTALL)
    if match:
        for item in re.finditer(r"<item>(.*?)</item>", match.group(1),
                                re.DOTALL):
            body = item.group(1)
            fm_match = re.search(r"<FUNCNAME>([^<]*)</FUNCNAME>", body,
                                 re.IGNORECASE)
            text_match = re.search(r"<SHORT_TEXT>([^<]*)</SHORT_TEXT>", body,
                                   re.IGNORECASE)
            if fm_match:
                name = fm_match.group(1).strip().upper()
                out["functions"].append(
                    (name,
                     html.unescape(text_match.group(1).strip())
                     if text_match else ""))
                out["interfaces"][name] = _parse_fm_interface(body)
    return out


# abapGit's parameter sections of one <FUNCTIONS><item>, with the FUPARAREF
# parameter type each one stands for.
_FM_SECTIONS = (("IMPORT", "RSIMP", "I"), ("CHANGING", "RSCHA", "C"),
                ("EXPORT", "RSEXP", "E"), ("TABLES", "RSTBL", "T"),
                ("EXCEPTION", "RSEXC", "X"))


def _parse_fm_interface(body: str) -> dict:
    """Read one function module's processing type and parameter list."""
    def flag(tag: str) -> str:
        m = re.search(rf"<{tag}>([^<]*)</{tag}>", body)
        return m.group(1).strip() if m else ""

    params = []
    for _section, row_tag, paramtype in _FM_SECTIONS:
        for row in re.finditer(rf"<{row_tag}>(.*?)</{row_tag}>", body,
                               re.DOTALL):
            fields = {m.group(1).upper(): html.unescape(m.group(2).strip())
                      for m in re.finditer(r"<(\w+)>([^<]*)</\1>",
                                           row.group(1))}
            fields["PARAMTYPE"] = paramtype
            params.append(fields)
    return {"remote_call": flag("REMOTE_CALL"),
            "update_task": flag("UPDATE_TASK"),
            "global_flag": flag("GLOBAL_FLAG"),
            "exception_classes": flag("EXCEPTION_CLASSES"),
            "params": params}


def uxx_include_source(include_prefix: str, functions: list) -> str:
    """The L<group>UXX include the function library generates: one INCLUDE
    per function module. abapGit does not serialize it, but SAPL<group>
    includes it -- without it the function pool does not compile."""
    lines = ["*****************************************************************",
             "*   THIS FILE IS GENERATED BY THE FUNCTION LIBRARY.             *",
             "*   NEVER CHANGE IT MANUALLY, PLEASE!                           *",
             "*****************************************************************"]
    for index, (funcname, _stext) in enumerate(functions, start=1):
        lines.append(f"INCLUDE {include_prefix}U{index:02d}.")
        lines.append(f'                    "{funcname}')
    return "\n".join(lines)


def _typing(prm: dict) -> str:
    """The typing clause of one parameter in the generated signature."""
    if prm.get("TYP"):
        if prm.get("REF_CLASS"):
            return f" TYPE REF TO !{prm['TYP']}"
        if prm.get("LINE_OF"):
            return f" TYPE LINE OF !{prm['TYP']}"
        return f" TYPE !{prm['TYP']}"
    if prm.get("DBFIELD"):
        return f" LIKE !{prm['DBFIELD']}"
    return ""


def signature_include_source(funcname: str, interface: dict) -> str:
    """
    The L<group>$<nn> include the function library generates for a function
    module: its signature as a `FUNCTION $$UNIT$$` statement. This -- not
    the `*"` comment block in the module's own source -- is what the
    compiler takes the parameters from; without it `FUNCTION <name>.` opens
    no processing block at all ("Statement is not accessible", every
    parameter unknown). Layout as generated on a real system (compare
    LSDTX$01 for RFC_READ_TABLE).
    """
    lines = ["*******************************************************************",
             "*   THIS FILE IS GENERATED BY THE FUNCTION LIBRARY.               *",
             "*   NEVER CHANGE IT MANUALLY, PLEASE!                             *",
             "*******************************************************************",
             f"FUNCTION $$UNIT$$ {funcname}",
             ""]
    params = interface.get("params") or []
    raising = "RAISING" if interface.get("exception_classes") else "EXCEPTIONS"
    for paramtype, heading in (("I", "IMPORTING"), ("E", "EXPORTING"),
                               ("C", "CHANGING"), ("T", "TABLES"),
                               ("X", raising)):
        rows = [prm for prm in params if prm["PARAMTYPE"] == paramtype]
        if not rows:
            continue
        lines.append(f"    {heading}")
        for prm in rows:
            if paramtype == "X":
                lines.append(f"       !{prm.get('EXCEPTION', '')}")
                continue
            name = prm.get("PARAMETER", "")
            if paramtype == "T":
                text = f"!{name}"
                if prm.get("DBSTRUCT"):
                    text += f" STRUCTURE !{prm['DBSTRUCT']}"
                else:
                    text += _typing(prm)
            else:
                passing = "REFERENCE" if prm.get("REFERENCE") else "VALUE"
                text = f"{passing}({name}){_typing(prm)}"
            if prm.get("DEFAULT"):
                text += f" DEFAULT {prm['DEFAULT']}"
            elif prm.get("OPTIONAL"):
                text += " OPTIONAL"
            lines.append(f"       {text}")
    lines[-1] += " ."
    return "\n".join(lines)


def collect_fugr_sources(src_dir: Path, obj_name: str, safe: str,
                         build_repos_key: BuildReposKey,
                         source_set_type: Type[dict]) -> dict[str, str]:
    """Collect function group includes and function modules."""
    sources = source_set_type()
    main_key = build_repos_key("FUGR", obj_name, "")           # [/NS/]SAPL<grp>
    include_prefix = build_repos_key("FUGR", obj_name, "?")[:-1]  # [/NS/]L<grp>
    fugr_xml = src_dir / f"{safe}.fugr.xml"
    meta = parse_fugr_xml(fugr_xml)
    sources.fugr_areat = meta["areat"]
    sources.fugr_functions = meta["functions"]
    sources.fugr_interfaces = meta["interfaces"]
    if not sources.fugr_functions:
        print(f"  WARNING: no FUNCTIONS list in {fugr_xml.name} -- "
              f"FM sources cannot be located")

    main_file = None
    fm_files = {}
    extra_includes = []
    for file_path in sorted(src_dir.glob(f"{safe}.fugr.*.abap")):
        part = file_path.name[len(f"{safe}.fugr."):-len(".abap")]
        name = part.replace("#", "/").upper()
        if name == main_key:
            main_file = file_path
        elif name.startswith(include_prefix):
            extra_includes.append((name[len(include_prefix):], file_path))
        else:
            fm_files[name] = file_path

    if main_file is not None:
        sources[main_key] = main_file.read_text(encoding="utf-8")
    else:
        print(f"  WARNING: no source file for {main_key} found -- "
              f"no main include")
    for suffix, file_path in extra_includes:
        sources[build_repos_key("FUGR", obj_name, suffix)] = \
            file_path.read_text(encoding="utf-8")
    if sources.fugr_functions:
        sources[build_repos_key("FUGR", obj_name, "UXX")] = \
            uxx_include_source(include_prefix, sources.fugr_functions)
    for index, (funcname, _stext) in enumerate(sources.fugr_functions, start=1):
        file_path = fm_files.get(funcname.upper())
        if file_path is not None:
            sources[build_repos_key("FUGR", obj_name, f"U{index:02d}")] = \
                file_path.read_text(encoding="utf-8")
            sources[build_repos_key("FUGR", obj_name, f"${index:02d}")] = \
                signature_include_source(
                    funcname, sources.fugr_interfaces.get(funcname, {}))
        else:
            print(f"  WARNING: FM {funcname} listed in "
                  f"{fugr_xml.name} but no {safe}.fugr.<fm>.abap found")
    return sources
